/** Status colours resolved for the active theme. Exposed via [taskStatusColors]. */
data class TaskStatusColors(
    val overdue: Color,
    val upcoming: Color,
    val ok: Color,
)

fun taskStatusColors(darkTheme: Boolean): TaskStatusColors =
    if (darkTheme) {
        TaskStatusColors(StatusOverdueDark, StatusUpcomingDark, StatusOkDark)
    } else {
        TaskStatusColors(StatusOverdueLight, StatusUpcomingLight, StatusOkLight)
    }

@Composable
fun CarCareoTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Material You dynamic colour on Android 12+; falls back to the brand palette.
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            WindowCompat.setDecorFitsSystemWindows(window, false)
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        content = content,
    )
}
